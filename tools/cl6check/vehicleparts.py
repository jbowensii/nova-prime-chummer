def hook_id(into):
    """Our kebab-case hook id of a Commlink6 hook (VEHICLE_BODY -> vehicle-body)."""
    return into.lower().replace("_", "-")


def part_cost(base, variant, into, rating, defs, variants):
    """The part's cost in its hook's unit, as a string: the usage value of the variant (else the item) on the hook it is
    embedded in; else its usage on any other hook (first by name); else 1. A $RATING formula is evaluated at the rating
    (1 unrated); one that needs the host ($$BODY, $$ARMOR ...) stays as printed, for the app to evaluate."""
    vu, iu = variants.get(base, {}).get(variant, {}), defs.get(base, {})
    raw = next((u[into] for u in (vu, iu) if into in u), None) if any(into in u for u in (vu, iu)) else None
    if raw is None:
        raw = next((u[s] for u in (vu, iu) for s in sorted(k for k in u if k) if u[s] is not None), "1")
    if raw is None or "$$" in raw:
        return raw or "1"
    v = canon.cl6_value(raw, int(rating) if str(rating or "").isdigit() else 1)
    return raw if v is None else f"{v:g}"


def _inline_sibling(vid, latest, others):
    """M7: the one inline part (geardef) another printing of this vehicle defines that the latest printing neither
    defines nor embeds, else None."""
    have = set(latest["geardef"]) | {e["ref"] for e in latest["embeds"]}
    cand = {g for o in others.get(vid, ()) for g in o["geardef"]} - have
    return next(iter(cand)) if len(cand) == 1 else None


def build(latest, others, defs, variants, part_ids, vehicle_ids):
    """(rows, unmatched) for the latest-printing records. latest {vehicle id: record}; others {vehicle id: [its other
    printings' records]}; defs/variants as embedmap.read_jar; part_ids {Commlink6 item id: our id}; vehicle_ids
    {Commlink6 vehicle id: [our ids]}. A row is one embed on one of our vehicles; sorted, so the file is stable."""
    rows, unmatched = [], []
    for vid, rec in sorted(latest.items()):
        mine = sorted(vehicle_ids.get(vid, ()))
        ids = {e["id"] for e in rec["embeds"] if e["id"]}
        built = []  # [(embed, row-or-None, why)]
        for i, e in enumerate(rec["embeds"], 1):
            ref, into = e["ref"], e["intoRef"]
            rule, base, rating, variant, note, review, override = (
                "M1",
                ref,
                e["rating"],
                e["variant"],
                "",
                "none",
                False,
            )
            why = ""
            if e["type"] not in (None, "GEAR"):
                why = f"embed type {e['type']} is not GEAR"
            elif ref not in defs:
                rule, base, r, v = embedmap.resolve_ref(ref, defs, variants)
                rating, variant = e["rating"] or r, e["variant"] or (v if isinstance(v, str) else None)
                if rule == "R-b ambiguous":
                    if (vid, ref) in OVERRIDES:
                        base, variant, note = OVERRIDES[vid, ref]
                        rule, override = "D9 override", True
                    else:
                        why = f"ambiguous variant of {base}: {', '.join(v)}"
                elif rule == "unresolved":
                    base = _inline_sibling(vid, rec, others)
                    if base:
                        rule, review = "M7", "needs-owner"
                        note = (
                            f"M7: undefined ref, mapped to the other printing's inline part {base} (CL6-reasoned stats)"
                        )
                    else:
                        why = "no rule resolves the ref"
                elif rule == "fuzzy (M6)":
                    review, note = "needs-owner", f"M6 fuzzy guess: {ref} -> {base}"
            if not why:
                if not mine:
                    why = "vehicle not matched to our catalog"
                elif base not in part_ids:
                    why = f"part {base} not matched to our catalog"
            if why:
                built.append((e, None, why))
                continue
            row = {
                "id": e["id"] or f"p{i}", "ref": part_ids[base], "hook": hook_id(into),
                "cost": part_cost(base, variant, into, rating, defs, variants),
                "parent": e["intoId"] if e["intoId"] in ids else "",
                "rating": rating, "variant": variant, "count": e["count"], "included": e["included"],
                "origin": "cl6", "review": review, "note": note, "cl6": f"{vid}/{ref}", "rule": rule,
            }  # fmt: skip
            if override:
                row["override"] = True
            built.append((e, {k: v for k, v in row.items() if v not in (None, "")}, ""))
        for e, row, why in built:
            if row is None:
                unmatched.append(
                    {"vehicle": mine, "cl6": f"{vid}/{e['ref']}", "hook": hook_id(e["intoRef"]), "why": why,
                     "review": "needs-owner"}
                )  # fmt: skip
            else:
                rows += [{"vehicle": ov, **row} for ov in mine]
    rows.sort(key=lambda r: r["vehicle"])  # (stable: embed order inside a vehicle)
    # A part id is unique within its vehicle: CL6 reuses an embed id inside a record, and a combined entry of ours takes
    # the parts of two CL6 vehicles. The later one gets "#n", the same rule partsOf (vehiclemods.ts) applies at run time.
    # No row is dropped; a child's `parent` keeps naming the first.
    seen = defaultdict(int)
    for r in rows:
        seen[r["vehicle"], r["id"]] += 1
        if seen[r["vehicle"], r["id"]] > 1:
            r["id"] += f"#{seen[r['vehicle'], r['id']]}"
    return rows, unmatched


def keys(results, published):
    """({Commlink6 item id: our id}, {Commlink6 vehicle id: [our ids]}, {our vehicle id: name}) from compare()
    results: an item takes the our-id
    its newest printing matched; a vehicle every our-id any of its printings matched (D7 gives them all one part list).
    """
    best, veh, names = {}, defaultdict(set), {}
    for r in results:
        if r["tag"] != "item" or not r["our_id"]:  # (matched via the optional package: no entry of ours)
            continue
        k = published.get(embedmap.SOURCE.get(r["book"], ""), "")
        if r["id"] not in best or k >= best[r["id"]][0]:
            best[r["id"]] = (k, r["our_id"])
        if r["kind"] == "vehicles" and r["our_kind"] == "vehicles":  # (not a weapon or sample entry the matcher took)
            veh[r["id"]].add(r["our_id"])
            names[r["our_id"]] = r["our_name"]
    return {i: v[1] for i, v in best.items()}, {i: sorted(v) for i, v in veh.items()}, names


def table(rows, unmatched):
    """The committed table's text: one row per line, so a regeneration diffs by row."""

    def lines(xs):
        return ",\n".join("  " + json.dumps(x, ensure_ascii=False) for x in xs)

    head = ' "_comment": ' + json.dumps(COMMENT, ensure_ascii=False)
    return f'{{\n{head},\n "rows": [\n{lines(rows)}\n ],\n "unmatched": [\n{lines(unmatched)}\n ]\n}}\n'


def gate(folder, data, latest):
    """(lines, ok): the Stage 2 gate on an import (`folder`, `<part>`s on its vehicles) against the table `data` and the
    D7 oracle (`latest`, embedmap.latest). (1) The oracle's placements (vehicle, ref, hook), each counted as many times
    as the vehicle embeds it (two cyberarms are two), are all in the table, as rows or as unmatched, with the same
    multiplicity: none lost, none invented, so a dropped duplicate fails. (2) Every vehicle of the import that has rows
    carries exactly the rows' (ref, hook, cost, parent) multiset, and no builtin of it survives except a slot grant.
    (3) Overrides read exactly 1."""
    import xml.etree.ElementTree as ET

    oracle = Counter((v, e["ref"], hook_id(e["intoRef"])) for v, r in latest.items() for e in r["embeds"])
    # (the synthesized powerplants, Stage 2b, are additive: no Commlink6 placement, so not in the oracle comparison;
    # they are still imported and checked below, and counted on their own line)
    cl6 = [r for r in data["rows"] if r.get("origin") != "synth"]
    synth = [r for r in data["rows"] if r.get("origin") == "synth"]

    def key(r):
        vid, _, ref = r["cl6"].partition("/")
        return vid, ref, r["hook"]

    # (a row is copied to each of our vehicles that is the Commlink6 vehicle: one copy's count is the placement's, and
    # the copies must agree)
    copies = defaultdict(Counter)
    for r in cl6:
        copies[key(r)][r["vehicle"]] += 1
    got = Counter({k: min(c.values()) for k, c in copies.items()})
    uneven = [k for k, c in copies.items() if len(set(c.values())) > 1]
    for u in data["unmatched"]:
        got[key(u)] += 1
    lost, invented = (
        oracle - got,
        got - oracle,
    )  # (Counter subtraction keeps the positive counts: a missing duplicate shows)
    ids, vehicles = set(), []
    for f in Path(folder).rglob("*.xml"):
        try:
            root = ET.parse(f).getroot()
        except ET.ParseError:
            continue
        ids |= {e.get("id") for e in root.iter() if e.get("id")}
        vehicles += list(root.iter("vehicle"))
    # (a row whose ref is no entry of this import, one only the optional CL6 module has, is skipped: vehicle held)
    held = {v for u in data["unmatched"] for v in u["vehicle"]} | {
        r["vehicle"] for r in data["rows"] if r["ref"] not in ids
    }
    held |= {r["vehicle"] for r in synth} - {r["vehicle"] for r in cl6}  # (only a synthesized part: its builtins stay)
    skipped = sum(1 for r in data["rows"] if r["ref"] not in ids)
    want, have, left, dangling = defaultdict(list), {}, 0, 0
    for r in data["rows"]:
        if r["ref"] in ids:
            want[r["vehicle"]].append((r["ref"], r["hook"], r["cost"], r.get("parent", "")))
    for v in vehicles:
        if v.get("id") in want:
            have[v.get("id")] = sorted(
                (p.get("ref"), p.get("hook"), p.get("cost") or "", p.get("parent") or "") for p in v.iter("part")
            )
            left += sum(1 for b in v.iter("builtin") if not b.get("slots") and v.get("id") not in held)
        dangling += sum(1 for p in v.iter("part") if p.get("ref") not in ids)
    bad = [v for v, parts in have.items() if parts != sorted(want[v])]
    over = len({r["cl6"] for r in data["rows"] if r.get("override")})
    lines = [
        f"oracle {len(oracle)} distinct placements ({sum(oracle.values())} with duplicates); table covers {len(got)} "
        f"({sum(got.values())}): lost {sum(lost.values())}, invented {sum(invented.values())}, "
        f"uneven copies {len(uneven)}",
        f"rows {len(data['rows'])} on {len(want)} vehicles; {len(have)} of them in this import, "
        f"{len(bad)} differ, {len(want) - len(have)} absent",
        f"held vehicles {len(held)} (an unmatched part, or {skipped} rows skipped for a ref only the optional module "
        f"has); dangling part refs {dangling}",
        f"unmatched {len(data['unmatched'])} (needs-owner); builtins left on vehicles with parts: {left}; "
        f"overrides {over}",
        f"synthesized (additive, not in the oracle): {len(synth)} powerplants "
        f"on {len({r['vehicle'] for r in synth})} vehicles",
    ]
    ok = not (lost or invented or uneven or bad or left or dangling or over != 1 or len(have) != len(want))
    return lines, ok


