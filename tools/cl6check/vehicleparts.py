SYNTH_NOTE = "Synthesized by the importer (not from a book or Commlink6)."
TAC = {"TAC_NET": "Tactical network"}  # (an electronics part's category by its Commlink6 subtype)
WEAPON = re.compile(r"WEAPON_(?:CLOSE_COMBAT|FIREARMS|VEHICLE|SPECIAL)$")


def read_inline(jar):
    """{part id: {vehicle, book, type, subtype, usage, weapon, name, page, vname, fixed}}: every <geardef> item of a
    vehicle record (P3), the first definition of an id, and each GLOBAL_PARTS item (a top-level item minted as if
    inline on its host vehicle), with the English names and pages of the part and of its vehicle (the jar's
    `item.<vehicle>.item.<part>` keys)."""
    import xml.etree.ElementTree as ET
    import zipfile

    out, text = {}, {}

    def add(g, vehicle, book, fixed=None):
        w = g.find("weapon")
        out.setdefault(
            g.get("id"),
            {"vehicle": vehicle, "book": book, "type": g.get("type"), "subtype": g.get("subtype"), "fixed": fixed,
             "usage": {u.get("slot"): u.get("value") for u in g.findall("usage")}, "avail": g.get("avail"),
             "hooks": {v.get("ref"): v.get("value") for v in g.findall("modifications/valmod")
                       if v.get("type") == "HOOK"},
             "weapon": dict(w.attrib) if w is not None else {}},
        )  # fmt: skip

    with zipfile.ZipFile(jar) as z:
        for n in sorted(z.namelist()):
            if n.endswith(".properties") and "/i18n/" in n and not reader.LANG_FILE.search(n.rsplit("/", 1)[1][:-11]):
                for ln in reader.decode(z.read(n)).splitlines():
                    k, _, v = ln.partition("=")
                    text.setdefault(k.strip(), v.strip())
            m = re.match(re.escape(reader.ROOT) + r"([^/]+)/data/.*\.xml$", n)
            if not m or reader.GERMAN.match(m[1]) or m[1] in ("placeholder", "icons"):
                continue
            try:
                root = ET.fromstring(z.read(n))
            except ET.ParseError:
                continue
            for el in root:
                if el.tag != "item" or not el.get("id"):
                    continue
                if el.find("vehicle") is not None:
                    for g in el.findall("geardef/item"):
                        add(g, el.get("id"), m[1])
                elif el.get("id") in GLOBAL_PARTS:
                    add(el, GLOBAL_PARTS[el.get("id")][0], m[1], GLOBAL_PARTS[el.get("id")][1])
    for pid, d in out.items():
        key = f"item.{pid}" if d["fixed"] else f"item.{d['vehicle']}.item.{pid}"
        d["name"] = d["fixed"] or text.get(key, pid)
        d["page"] = text.get(key + ".page") or text.get(f"item.{d['vehicle']}.page")
        d["vname"] = text.get(f"item.{d['vehicle']}", d["vehicle"])
    return out


def inline_entries(inline, part_ids, vehicle_ids, names=None):
    """({part id: our id}, {recipe id: [add rows]}): a catalog entry (an override `add` row of the book of the part's
    first vehicle of ours, gen vehicle-part) for each inline part (P3) that has no entry of ours yet, so it keys and
    imports as a part. Stats are the geardef's own; price 0 (in the vehicle's), no text. A part named only by its role
    gets OUR vehicle's name before it (never Commlink6's longer one: the checker's name-contained stage would take such
    an entry for the vehicle's record); a global part keeps its fixed name."""
    from importer.sr6.ids import slug

    ids, rows = {}, defaultdict(list)
    for pid, d in sorted(inline.items()):
        mine = sorted(vehicle_ids.get(d["vehicle"], ()))
        if pid in part_ids or not mine or not d["page"] or not d["page"].isdigit():
            continue
        src = mine[0].split(".")[0]
        vname = (names or {}).get(mine[0]) or d["vname"]
        own = set(vname.lower().split()) <= set(d["name"].lower().split())
        name = d["name"] if d.get("fixed") or own else f"{vname} {d['name']}"
        w = d["weapon"]
        kind = (
            "weapons"
            if WEAPON.match(d["type"] or "") and w
            else "electronics" if d["type"] == "ELECTRONICS" else "gear"
        )
        category = {"weapons": "Vehicle weapon", "gear": "Vehicle modification"}.get(
            kind, TAC.get(d["subtype"], "Electronics")
        )
        attrs = {"category": category, "cost": "0", "class": f"{d['type']}/{d['subtype']}", "modonly": "true"}
        if m := re.fullmatch(r"(\d+)([A-Z])", d.get("avail") or ""):
            attrs["avail"] = f"{m[1]}({m[2]})"
        if kind == "weapons":
            bands = [b.strip() or "—" for b in w.get("attack", "").split(",")]
            attrs |= {k: v for k, v in {
                "dv": w.get("dmg"), "ar": "/".join(bands) if any(b != "—" for b in bands) else None,
                "modes": w.get("mode"), "ammo": w.get("ammo"), "skill": SKILL.get(w.get("skill", "")),
                "spec": w["spec"].split("/")[-1].replace("_", " ").title() if w.get("spec") else None,
            }.items() if v}  # fmt: skip
        kids = [{"tag": "fits", "attrs": {"slot": hook_id(h)}} for h in d["usage"] if h]
        if d.get("fixed"):  # (a global part's own hook grant; a geardef mount's is the host's)
            kids += [{"tag": "slot", "attrs": {"id": hook_id(h), "value": v}} for h, v in d.get("hooks", {}).items()]
        rows[src].append(
            {"cl6": name, "kind": kind, "gen": "vehicle-part",
             "add": {"page": int(d["page"]), "attrs": attrs, "kids": kids}}
        )  # fmt: skip
        ids[pid] = f"{src}.{slug(name)}"
    return ids, rows


def write_entries(rows, root=OVERRIDES_DIR):
    """The add rows into the books' override tables: each table keeps its other rows and swaps its earlier
    gen=vehicle-part ones for the new. {recipe id: rows written}."""
    done = {}
    for stem in sorted(rows.keys() - {p.stem for p in Path(root).glob("*.json")}):
        (Path(root) / f"{stem}.json").write_text("[]\n", encoding="utf8", newline="\n")  # (a book with no table yet)
    for path in sorted(Path(root).glob("*.json")):
        old = json.loads(path.read_text(encoding="utf8"))
        keep = [r for r in old if r.get("gen") != "vehicle-part"]
        new = rows.get(path.stem, [])
        if len(keep) != len(old) or new:
            lines = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in keep + new)
            path.write_text("[\n" + lines + "\n]\n", encoding="utf8", newline="\n")
        done[path.stem] = len(new)
    return {k: v for k, v in done.items() if v}


def _stat(v, key):
    """A vehicle's stat as a number (its leading digits), else 0."""
    m = re.match(r"\d+(?:\.\d+)?", (v["attrs"].get(key) or "").strip())
    return float(m[0]) if m else 0.0


def powerplants(vehicles, taken=()):
    """Stage 2b, ruling D3 (docs/analysis/sr6-vehicle-decomposition.md): ([part rows], {book: [add rows]}) with one
    synthesized `<Vehicle> Powerplant` for each self-propelled vehicle of ours (a Speed or an Acceleration stat above
    0), and none for one that cannot move (a trailer). vehicles: [{id, name, page, attrs}]. Hook vehicle-powertrain;
    size max(0.5, round(Body / 3)): a heuristic of this app, not Commlink6's or a book's, so the part is origin synth
    and review needs-owner. Price 0 (included in the vehicle, D8). The entry says what it stands for in its Speed and
    Acceleration. Never claims a source."""
    rows, add, seen = [], defaultdict(list), set(taken)
    for v in sorted(vehicles, key=lambda e: e["id"]):
        a = v["attrs"]
        if not (_stat(v, "topSpeed") > 0 or _stat(v, "accel") > 0):
            continue
        body = _stat(v, "body")
        size = max(0.5, float(int(body / 3 + 0.5)))  # (round half up; Python's round() would go to even)
        src, name = v["id"].split(".")[0], f"{v['name']} Powerplant"
        # (its own id, the vehicle's id tail + -powerplant: unique as the vehicle's is, and never the vehicle's own
        # id, as slug(name), cut at 60 letters, could be for a long name)
        pid = f"{v['id'].split('.', 1)[1]}-powerplant"
        ref = f"{src}.{pid}"
        if ref in seen:
            raise ValueError(f"two powerplants would be {ref}: name {name!r}")
        seen.add(ref)
        why = f"synthesized powerplant, size max(0.5, round(Body {body:g} / 3)): the importer's own, not from a book"
        rows.append(
            {"vehicle": v["id"], "id": "pp", "ref": ref, "hook": "vehicle-powertrain", "cost": f"{size:g}",
             "origin": "synth", "review": "needs-owner", "rule": "D3 synthesized", "note": why}
        )  # fmt: skip
        page = str(v.get("page") or "")
        text = f"Powerplant: Speed {a.get('topSpeed') or '?'}, Acceleration {a.get('accel') or '?'}. "
        attrs = {
            "category": "Vehicle modification",
            "cost": "0",
            "class": "MOD_POWER/MOD_PROPULSION",
            "modonly": "true",
        }
        kids = [
            {"tag": "fits", "attrs": {"slot": "vehicle-powertrain"}},
            {"tag": "note", "attrs": {"field": "powerplant"}, "text": text + SYNTH_NOTE},
        ]  # fmt: skip
        add[src].append(
            {"cl6": name, "kind": "gear", "gen": "vehicle-part",
             "add": {"page": int(page) if page.isdigit() else 1, "id": pid, "attrs": attrs, "kids": kids}}
        )  # fmt: skip
    return rows, add


def main(argv):
    """Generate the table from the jar and an import; prints the counts and the unmatched summary."""
    args = list(argv)
    opt = {a: args.pop(args.index(a) + 1) for a in ("--jar", "--ours", "--out") if a in args}
    jar = reader.find_jar(opt.get("--jar"))
    if jar is None:
        print("cl6check gen-vehicle-parts: no Commlink6 jar (--jar or $CL6_JAR): skipped.")
        return 0
    if "--ours" not in opt:
        print("cl6check gen-vehicle-parts: --ours <import folder> is required.", file=sys.stderr)
        return 2
    from importer.sr6.ids import slug
    from tools.cl6check.__main__ import compare

    vehicles, defs, variants = embedmap.read_jar(jar)
    published = corpus.published(embedmap.SOURCES)
    latest = embedmap.latest(vehicles, published)
    others = defaultdict(list)
    for v in vehicles:
        if v is not latest[v["id"]]:
            others[v["id"]].append(v)
    recs, _ = reader.read(jar)
    mine = ours.load(opt["--ours"])
    results, _, _ = compare([canon.canonical(r) for r in recs], mine, pdf=False)
    part_ids, vehicle_ids, vnames = keys(results, published)
    made, add = inline_entries(read_inline(jar), part_ids, vehicle_ids, vnames)
    part_ids |= made
    rows, unmatched = build(latest, others, defs, variants, part_ids, vehicle_ids)
    taken = set(part_ids.values()) | {f"{k}.{slug(r['cl6'])}" for k, rs in add.items() for r in rs}
    pp_rows, pp_add = powerplants([e for s in mine.values() for e in s.entries if e["kind"] == "vehicles"], taken)
    rows = sorted(
        rows + pp_rows, key=lambda r: r["vehicle"]
    )  # (stable: a vehicle's Commlink6 parts, then its powerplant)
    for k, rs in pp_add.items():
        add[k] += rs
    print(f"synthesized powerplants {len(pp_rows)} (additive)")
    rows_cl6 = [r for r in rows if r.get("origin") != "synth"]
    n = len({r["cl6"] for r in rows_cl6})
    print(f"rows {len(rows)} on {len({r['vehicle'] for r in rows})} of our vehicles ({n} distinct CL6 placements)")
    print(f"overrides {len({r['cl6'] for r in rows_cl6 if r.get('override')})}; unmatched {len(unmatched)}:")
    why = defaultdict(list)
    for u in unmatched:
        why[re.sub(r"part \S+ not", "part not", u["why"])].append(u["cl6"])
    for w, xs in sorted(why.items()):
        print(f"  {len(xs):4}  {w}  e.g. {', '.join(xs[:4])}")
    if "--dry" not in args:
        out = Path(opt.get("--out", OUT))
        out.write_text(table(rows, unmatched), encoding="utf8", newline="\n")
        print(
            "wrote",
            out,
            "; entries",
            write_entries(add) if "--out" not in opt else f"(not written: --out) {sum(map(len, add.values()))}",
        )
    return 0


