"""Stage 2 of the vehicle decomposition plan (docs/analysis/sr6-vehicle-decomposition.md, "Stage 2: importer"):

  python -m tools.cl6check gen-vehicle-parts --ours <import> [--jar <jar>] [--out <file>] [--dry]

The app importer is PDF-based and never reads the jar, so the per-vehicle factory parts are baked here into a committed,
generated table, importer/sr6/classes/vehicle_parts.json (owner ruling, 2026-10-28, option a: a narrow exception to
"no Commlink6 data in the repo"; game-mechanical hook/slot/cost only). It takes each vehicle's latest-printing embed set
(D7, embedmap.latest), resolves every ref by the plan's rules (M1 defined; M2-M6 embedmap.resolve_ref; M7 the sibling
printing's inline part; the one ruled override, D9), and keys each part and vehicle to OUR catalog ids with the matcher
the checker uses (`compare`, match.py). What cannot be resolved or keyed goes on the table's `unmatched` list, flagged
needs-owner: never dropped, never written as a blank row. `build` is the pure core (the unit test feeds it
invented data).
"""

