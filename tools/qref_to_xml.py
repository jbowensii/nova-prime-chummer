"""Quick-reference sheets (Base, Magic, Matrix, Vehicles; design by felipedaen) -> rules.

The committed public/data/rules.xml keeps titles, sections and effect links only; the
sheets' text goes to a private texts file (default .extract/private/texts/qref.xml),
like the Shadow Amps descriptions. Source "QREF" (sources.xml: published, not canon).

Usage: python tools/qref_to_xml.py "<folder with 1358228-SRA2_-_*.md>" [public/data/rules.xml] [texts.xml]
"""
import os
import re
import sys
from xml.sax.saxutils import escape

SHEETS = ["Base", "Magic", "Matrix", "Vehicles"]
# rule title (lowercase) -> amp effects it explains; shown as hover help on those effects
EFFECTS = {
    "vr cold-sim": "vr-cold", "vr hot-sim": "vr-hot", "captain’s chair": "rcc", "jump in": "vcr",
    "astral perception": "awk-astral-perception", "astral projection": "awk-astral-projection",
    "sustained spell (s)": "sustain-spell", "summoning": "summon-spirit awk-conjuring", "spellcasting": "awk-sorcery",
    "firewall": "firewall-plus", "risk reduction (rr)": "rr-skill rr-spec rr-attr rr-attr",
    "extra action": "init-1 init-2 init-3",
}


def slug(s):
    s = s.lower().replace("’", "").replace("'", "")
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:50]


def clean(s):
    s = re.sub(r"~~-~~", "-", s).replace("~~=~~", "=").replace(" ", " ")
    s = re.sub(r"<u>|</u>|\*\*|~~", "", s)
    return re.sub(r"\s+", " ", s).strip()


def parse(sheet, md):
    rules, section, page, cur = [], "", 0, None
    for line in md.splitlines():
        t = line.strip()
        if not t or t.startswith("design by") or t.startswith("- design by"):
            continue
        if re.match(r"# (?!#)", t):  # each printed page starts with the sheet title
            page += 1
            continue
        m = re.match(r"#{2,3} (.+)", t)
        if m:
            section = clean(m.group(1)).title()
            cur = None
            continue
        m = re.match(r"(?:- )?\*\*([^*]+?):?\*\*:?\s*(.*)", t)
        if m and not re.match(r"(?:- )?\*\*\d\.", t):
            cur = {"title": clean(m.group(1)).rstrip(":"), "section": section, "page": page, "text": [clean(m.group(2))]}
            rules.append(cur)
            continue
        if cur is not None:  # sub-bullet or continuation of the previous rule
            cur["text"].append(clean(t.lstrip("- ")))
        else:  # untitled lines under a heading (Cybercombat steps): one rule named after the section
            cur = {"title": section, "section": section, "page": page, "text": [clean(t.lstrip("- "))]}
            rules.append(cur)
    return rules


def main(folder, out=os.path.join("public", "data", "rules.xml"), text_path=".extract/private/texts/qref.xml"):
    entries, texts, ids = [], [], set()
    for sheet in SHEETS:
        md = open(os.path.join(folder, f"1358228-SRA2_-_{sheet}.md"), encoding="utf8").read()
        for r in parse(sheet, md):
            rid = f"{sheet.lower()}-{slug(r['title'])}"
            base, n = rid, 2
            while rid in ids:
                rid, n = f"{base}-{n}", n + 1
            ids.add(rid)
            fx = EFFECTS.get(r["title"].lower())
            fx_attr = f' effects="{" ".join(dict.fromkeys(fx.split()))}"' if fx else ""
            entries.append(f'  <rule id="{rid}" sheet="{sheet.lower()}" section="{escape(r["section"])}"{fx_attr} source="QREF" page="{max(r["page"], 1)}">'
                           f'<title>{escape(r["title"])}</title><text></text></rule>')
            body = " ".join(x for x in r["text"] if x)
            if body:
                texts.append(f'  <text of="rules" id="{rid}">{escape(body)}</text>')
    with open(out, "w", encoding="utf8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n'
                "<!-- Rules reference from the quick-reference sheets (Base, Magic, Matrix, Vehicles; design by felipedaen).\n"
                "     Generated by tools/qref_to_xml.py. The text is private (custom/texts/qref.xml); effects= links a\n"
                "     rule to the amp effects it explains, for hover help. -->\n"
                '<ca2:data xmlns:ca2="urn:chummer-anarchy2:data:1" kind="rules" version="1">\n'
                + "\n".join(entries) + "\n</ca2:data>\n")
    os.makedirs(os.path.dirname(text_path), exist_ok=True)
    with open(text_path, "w", encoding="utf8", newline="\n") as f:
        f.write('<?xml version="1.0" encoding="UTF-8"?>\n<!-- PRIVATE: quick-reference sheet text. Do not commit. -->\n'
                '<ca2:data xmlns:ca2="urn:chummer-anarchy2:data:1" kind="texts" version="1">\n' + "\n".join(texts) + "\n</ca2:data>\n")
    print(f"rules {len(entries)}, texts {len(texts)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
