"""The rows applied to a book's catalog xml: an add row's new entry (_add), the id rows' values, effects and children
(_set_by_id), and the remove, split, merge, rename and move_kind ops (_ops); dump() writes a file back as it was."""

import copy
import re
import sys

from importer import xmlio
from importer.sr6.ids import slug
from importer.sr6.regroup import norm
from importer.sr6.resolve import add_kid

from .schema import allowed, fit

UNMATCHED_DROPS = (
    []
    # (the book rows' drops that took out nothing, [(entry id, drop)]: a row written against a reader that has changed
    # since; tests and tools/ check it stays empty)
)


def dump(old, root):
    """The xml of `root` as the file `old` had it: its header comment (`Generated by the importer …`) kept."""
    from lxml import etree

    lead = re.match(r"(?:<\?xml[^>]*\?>\s*)?((?:<!--.*?-->\s*)*)", old or "", re.S).group(1)
    return xmlio.HEAD + lead + etree.tostring(root, encoding="unicode").rstrip(chr(10)) + chr(10)


def _add(out, name, r, source):
    """Create row r's entry in out[name] (the kind's file, made when the book has none); a no-op when its id is
    there."""
    from lxml import etree

    from importer.sr6 import KINDS, NS

    a, kind = r["add"], r["kind"]
    if source is None:
        print(f"override {r['cl6']}: add needs a recipe id", file=sys.stderr)
        return
    if out.get(name):
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
    else:
        root = etree.fromstring(f'<sr6:data xmlns:sr6="{NS}" kind="{kind}" version="1"/>'.encode())
    ename = a.get("name", r["cl6"])
    eid = a.get("id") or slug(ename)  # (an id of its own when another entry has the name: a rigger program Encryption)
    if any(e.get("id") == eid for e in root if isinstance(e.tag, str)):
        print(f"override {r['cl6']}: {eid} already in {name}, left as is", file=sys.stderr)
        return
    e = etree.SubElement(
        root,
        KINDS[kind],
        {"id": eid, "source": source, "page": str(a["page"]), **{k: str(v) for k, v in a.get("attrs", {}).items()}},
    )
    etree.SubElement(e, "name").text = ename
    for k in a.get("kids", []):
        etree.SubElement(e, k["tag"], {x: str(v) for x, v in k.get("attrs", {}).items()}).text = k.get("text")
    out[name] = dump(out.get(name), root)


def _refile(out, rows):
    """The id rows with `kind` the file that holds the id: a row filed under Commlink6's kind (gear for a weapon
    accessory) goes to the one other kind file with the id; an id in none or in several stays as it is (reported by the
    caller)."""
    from lxml import etree

    from importer.sr6 import KINDS

    ids = {}  # (kind -> its top-level ids), read once for the files a row needs

    def of(kind):
        if kind not in ids:
            xml = out.get(f"{kind}.xml")
            ids[kind] = (
                {
                    e.get("id")
                    for e in etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", xml).encode("utf8"))
                    if isinstance(e.tag, str)
                }
                if xml
                else set()
            )
        return ids[kind]

    done, ambiguous = [], []
    for r in rows:
        if r["id"] not in of(r["kind"]):
            other = [
                k
                for k in KINDS
                if k != r["kind"]
                and r["id"] in of(k)
                and set(r.get("set", {})) <= (allowed(k) or set(r.get("set", {})))
            ]  # (never to a kind whose schema lacks the attribute: a class on a rules entry)
            if len(other) == 1:
                r = {**r, "kind": other[0]}
            elif other:
                ambiguous.append(f"{r['kind']}.xml:{r['id']} in {', '.join(other)}")
        done.append(r)
    if ambiguous:
        print(
            f"override: {len(ambiguous)} id rows name an id several kind files hold, "
            f"left unfiled ({'; '.join(ambiguous[:4])})",
            file=sys.stderr,
        )
    return done


def _set_by_id(out, rows):
    """The id rows applied: out[<kind>.xml] with each entry of an id the rows name given its attributes."""
    from lxml import etree

    rows = fit(_refile(out, rows))
    want, forms, vals, kids, effs, drops = {}, {}, {}, {}, {}, {}
    for r in sorted(rows, key=lambda r: r.get("gen") == "errata"):  # (an errata's values last: they win)
        if r.get("effects"):
            effs.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], []).extend(
                (
                    {
                        **a,
                        "gen": r["gen"],
                        **({"book": True, "add_only": bool(r.get("keep"))} if r["gen"] == "book" else {}),
                    }
                    if r.get("gen") in ("cl6", "book")
                    else a
                )
                for a in r["effects"]
            )  # (a Commlink6 or book row's effect says so)
        if r.get("drops"):
            drops.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], []).extend(r["drops"])
        want.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], {}).update(r.get("set", {}))
        if r.get("kids"):
            kids.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], []).extend(r["kids"])
        if r.get("gen") in ("value", "family", "errata", "owner"):
            forms.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], {}).update(r.get("formula", {}))
            vals.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], set()).update(r.get("set", {}))
    missing = []
    for name, ids in want.items():
        if not out.get(name):
            missing += [f"{name}:{i}" for i in ids]
            continue
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
        seen = set()
        for e in root:
            if isinstance(e.tag, str) and e.get("id") in ids:
                seen.add(e.get("id"))
                for k, v in ids[e.get("id")].items():
                    if v is None:  # (an errata drops the attribute)
                        e.attrib.pop(k, None)
                    else:
                        e.set(k, str(v))
                for d in drops.get(name, {}).get(
                    e.get("id"),
                    [],
                    # (a book row takes out the effect it names: those attributes equal, the others it leaves
                    # out absent)
                ):
                    gone = [
                        c
                        for c in e
                        if c.tag == "effect"
                        and all(
                            c.get(k) == (str(d[k]) if k in d else None)
                            for k in ("target", "op", "value", "switch", "when", "spec", "affects", "from")
                        )
                    ]
                    if not gone:
                        UNMATCHED_DROPS.append((e.get("id"), d))
                        print(f"override {e.get('id')}: the drop {d} matches no effect", file=sys.stderr)
                    for c in gone:
                        e.remove(c)
                book = effs.get(name, {}).get(e.get("id"), [])
                taken = {(a["target"], a.get("op")) for a in book if a.get("book") and not a.get("add_only")}
                for c in [
                    c
                    for c in e
                    if c.tag == "effect"
                    and (c.get("target"), c.get("op")) in taken
                    and c.get("gen") not in ("cl6", "book")
                ]:
                    e.remove(
                        c
                        # (a book row's effects replace the reader's of the same target and operation, as a
                        # Commlink6 row's do, unless the row says `keep`)
                    )
                for a in book:  # (replaces the same target's effect, or the one "replaces" names)
                    if not a.get("book"):
                        for c in [
                            c
                            for c in e
                            if c.tag == "effect"
                            and c.get("target") in (a.get("replaces", a["target"]), a["target"])
                            and (not a.get("op") or c.get("op") == a["op"])
                        ]:
                            e.remove(c)
                    attrs = {x: str(v) for x, v in a.items() if x not in ("replaces", "book", "add_only", "keep")}
                    if a.get("keep"):
                        attrs.pop(
                            "gen", None
                        )  # (the reader's own effect, restated so the replacement leaves it: no mark)

                    def same(c, attrs=attrs):
                        return c.tag == "effect" and all(
                            c.get(k) == attrs.get(k)
                            for k in ("target", "op", "value", "when", "switch", "spec", "affects")
                        )

                    if any(same(c) for c in e):
                        continue  # (applied again, or the replaced effect gone: the effect is there once)
                    c = etree.Element("effect", attrs)
                    e.insert(
                        len(e) - (1 if len(e) and e[-1].tag == "text" else 0), c
                    )  # (the tail group's: after the kind's own children (infected, step, modifier), before the <text>)
                for k in vals.get(name, {}).get(e.get("id"), ()):
                    for c in [c for c in e if c.tag in ("formula", "issue", "found") and c.get("field") == k]:
                        e.remove(c)  # (the value they described is replaced)
                    if k == "karma":
                        e.attrib.pop("karmaMax", None)
                for k in kids.get(name, {}).get(
                    e.get("id"), []
                ):  # (a structure child the entry lacks, before its <text>)
                    attrs = {x: str(v) for x, v in k.get("attrs", {}).items()}
                    if any(
                        c.tag == k["tag"] and dict(c.attrib) == attrs and (c.text or "") == (k.get("text") or "")
                        for c in e
                    ):
                        continue
                    c = etree.Element(k["tag"], attrs)
                    c.text = k.get("text")
                    if "replaces" in k:  # (an owner row's correction: that child, in its place)
                        old = next(
                            (
                                x
                                for x in e
                                if x.tag == k["tag"] and all(x.get(a) == str(v) for a, v in k["replaces"].items())
                            ),
                            None,
                        )
                        if old is None:
                            print(
                                f"override {e.get('id')}: no <{k['tag']}> {k['replaces']} to replace", file=sys.stderr
                            )
                        else:
                            e.replace(old, c)
                        continue
                    t = e.find("text")
                    e.insert(list(e).index(t) if t is not None else len(e), c)
                for k, expr in forms.get(name, {}).get(e.get("id"), {}).items():
                    f = etree.Element("formula", {"field": k})
                    f.text = expr
                    e.insert(sum(1 for c in e if c.tag in ("name", "alias", "formula")), f)
        missing += [f"{name}:{i}" for i in ids if i not in seen]
        out[name] = dump(out[name], root)
    if missing:
        print(
            f"override: {len(missing)} id rows found no entry "
            f"({', '.join(missing[:6])}{' ...' if len(missing) > 6 else ''})",
            file=sys.stderr,
        )


MOVE_DROP = {
    ("gear", "weapons"): {
        "capacity",
        "karma",
        "per",
        "slots",
        "energy",
    },  # (an entry's attributes the target kind's schema lacks)
    ("armor", "gear"): {"defense", "social"},
}
SPECS = {"BLADES": "Blades", "CLUBS": "Clubs", "UNARMED": "Unarmed", "OTHER_CLOSE": "Other"}


def _load(out, name, kind):
    """(the file's root, its xml as it was): a new file when there is none."""
    from lxml import etree
    from importer.sr6 import NS

    if out.get(name):
        return etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8")), out[name]
    return etree.fromstring(f'<sr6:data xmlns:sr6="{NS}" kind="{kind}" version="1"/>'.encode()), ""


def _find(root, eid):
    return next((e for e in root if isinstance(e.tag, str) and e.get("id") == eid), None)


def _ops(out, rows):
    """The remove, merge, rename and move_kind rows applied, in that order (a merge before the move that files its
    target as a weapon). A row whose entry isn't there is reported once, nothing guessed."""
    from lxml import etree

    from importer.sr6 import KINDS

    lost = []
    for r in (x for x in rows if x.get("remove")):
        name = f"{r['kind']}.xml"
        root, old = _load(out, name, r["kind"])
        e = _find(root, r["id"])
        if e is None:
            lost.append(f"remove {name}:{r['id']}")
            continue
        root.remove(e)
        out[name] = dump(old, root)
    for r in (x for x in rows if x.get("split")):
        name = f"{r['kind']}.xml"
        root, old = _load(out, name, r["kind"])
        e = _find(root, r["id"])
        if e is None:
            lost.append(f"split {name}:{r['id']}")
            continue
        at = list(root).index(e)
        for n, part in enumerate(r["split"]):
            c = copy.deepcopy(e)
            c.set("id", part["id"])
            c.find("name").text = part["name"]
            for a in [a for a in c.findall("alias") if not a.get("id")]:
                c.remove(a)  # (the whole row's other names)
            for k, v in part.get("set", {}).items():
                if v is None:  # (null drops the attribute, as an errata's)
                    c.attrib.pop(k, None)
                else:
                    c.set(k, str(v))
                for x in [x for x in c if x.tag in ("formula", "issue", "found") and x.get("field") == k]:
                    c.remove(x)
            if note := part.get("note"):
                x = etree.Element("note", {"field": note["field"]})
                x.text = note["text"]
                c.insert(sum(1 for x in c if x.tag in ("name", "alias", "formula", "issue", "found")), x)
            root.insert(at + n, c)
        root.remove(e)
        out[name] = dump(old, root)
    for r in (x for x in rows if "merge" in x):
        m = r["merge"]
        into, src = f"{r['kind']}.xml", f"{m.get('from_kind', r['kind'])}.xml"
        ri, oi = _load(out, into, r["kind"])
        rs, os_ = _load(out, src, m.get("from_kind", r["kind"]))
        a, b = _find(ri, m["into"]), _find(rs, m["from"])
        if a is None or b is None:
            lost.append(f"merge {into}:{m['into']} <- {src}:{m['from']}")
            continue
        for k, v in b.attrib.items():
            if k not in ("id", "source", "page", "class", "group") and not a.get(k) and v:
                a.set(k, v)
        rs.remove(b)
        out[into], out[src] = dump(oi, ri), dump(os_, rs)
    for r in (x for x in rows if "rename" in x):
        name = f"{r['kind']}.xml"
        root, old = _load(out, name, r["kind"])
        e = _find(root, r["id"])
        if e is None:
            lost.append(f"rename {name}:{r['id']}")
            continue
        n = e.find("name")
        was = (n.text or "").strip()
        if was != r["rename"]:
            n.text = r["rename"]
            if (
                r.get("alias", True)
                and was
                and norm(was) not in {norm(x.text or "") for x in e.findall("alias")} | {norm(r["rename"])}
            ):
                add_kid(e, "alias", {}, was)
            out[name] = dump(old, root)
    for r in (x for x in rows if "move_kind" in x):
        m = r["move_kind"]
        src, dst = f"{m['from']}.xml", f"{m['to']}.xml"
        if (m["from"], m["to"]) not in MOVE_DROP:
            lost.append(f"move_kind {m['from']} to {m['to']} (only gear to weapons, armor to gear)")
            continue
        rs, os_ = _load(out, src, m["from"])
        rd, od = _load(out, dst, m["to"])
        e = _find(rs, m["id"])
        if e is None:
            lost.append(f"move_kind {src}:{m['id']}")
            continue
        if _find(rd, m["id"]) is not None:
            lost.append(f"move_kind {m['id']}: {dst} has it already")
            continue
        e.tag = KINDS[m["to"]]
        for k in MOVE_DROP[m["from"], m["to"]]:
            e.attrib.pop(k, None)
        if m["to"] == "weapons":  # (a melee weapon: Close Combat, its specialization from its class)
            sub = (e.get("class") or "").split("/")[-1]
            spec = SPECS.get(sub) or SPECS.get((e.get("type") or "").upper())
            e.set("skill", "Close Combat")
            if spec:
                e.set("spec", spec)
        rs.remove(e)
        rd.append(e)
        out[src], out[dst] = dump(os_, rs), dump(od, rd)
    if lost:
        print(
            f"override: {len(lost)} op rows found no entry ({'; '.join(lost[:6])}{' ...' if len(lost) > 6 else ''})",
            file=sys.stderr,
        )
