"""Per-book override tables (importer/sr6/overrides/<recipe id>.json, lower case; absent = empty): a last resort, applied
after the import reads a book. Each row maps a Commlink6 name to our item(s), source-scoped (one table per recipe):
  {"cl6": "<Commlink6's name>", "kind": "<catalog file stem>", "ours": ["<our entry's printed name>", ...],
   "set": {"<attribute>": "<value taken from Commlink6>"}}   ("set" optional)
It adds the Commlink6 name as an <alias> child (a name only) to each entry of `ours`, and sets the listed attributes.
A row with "add" instead of "ours" CREATES an entry the books print only inside other items' text (Commlink6 has it):
  {"cl6": "<Commlink6's name>", "kind": "<catalog file stem>", "add": {"page": <int>, "attrs": {...rule data from
   Commlink6}, "kids": [{"tag": "effect|choice|alias|...", "attrs": {...}}], "name": "<optional, default cl6>"}}
id = slug(name) (scoped to the source by the importer); an id already in the file is left alone (logged). No text of
any kind is written: the entry's description, if the book has one, comes from the texts step. "text_from": "<heading
name>" (a name, never text) in an add row gives the entry the description the book's text already has under that
heading (`texts()`: the owner's PDF text of the catalog entry of that name, copied to the new entry).
A row with "id" (an entry's unscoped id, the importer's own) and "set" {"class": "<TYPE/SUBTYPE>"} sets Commlink6's
classification on that entry (rows made by tools/cl6check/classmap.py carry "gen": "class"); "class" is the only attribute
such a row may set, and an id no entry has is reported once on stderr, nothing guessed.
A description is never an override: "set" and "add" refuse a text field. See docs/sr6-data-format.md."""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr, unescape

from importer import xmlio
from importer.sr6.ids import slug
from importer.sr6.regroup import norm
from importer.sr6.resolve import _add_kid

DIR = Path(__file__).with_name("overrides")
SETTABLE = {"class"}  # (what an id row may set)
CLASS_KEY = re.compile(r"[A-Za-z0-9_]+(/[A-Za-z0-9_]+)?")
NO_TEXT = {"description", "desc", "text", "summary"}  # (descriptions come from the owner's PDF, never from here)


def dump(old, root):
    """The xml of `root` as the file `old` had it: its header comment (`Generated by the importer …`) kept."""
    from lxml import etree
    lead = re.match(r"(?:<\?xml[^>]*\?>\s*)?((?:<!--.*?-->\s*)*)", old or "", re.S).group(1)
    return xmlio.HEAD + lead + etree.tostring(root, encoding="unicode").rstrip(chr(10)) + chr(10)


def check(rows):
    for r in rows:
        if bad := NO_TEXT & {k.lower() for k in r.get("set", {})}:
            raise ValueError(f"override of {r.get('cl6')} sets a description field ({sorted(bad)})")
        if "id" in r:
            if not r.get("set") or set(r["set"]) - SETTABLE or not all(CLASS_KEY.fullmatch(str(v)) for v in r["set"].values()):
                raise ValueError(f"override of {r.get('id')}: an id row sets {sorted(SETTABLE)} only")
        if a := r.get("add"):
            names = {k.lower() for k in a} | {k.lower() for k in a.get("attrs", {})} | {k["tag"].lower() for k in a.get("kids", [])}
            if bad := NO_TEXT & names:
                raise ValueError(f"override of {r.get('cl6')} adds a description field ({sorted(bad)})")
            if not (isinstance(a.get("text_from", ""), str) and len(a.get("text_from", "")) <= 80 and chr(10) not in a.get("text_from", "")):
                raise ValueError(f"override of {r.get('cl6')}: text_from is a heading name")
            if not isinstance(a.get("page"), int):
                raise ValueError(f"override of {r.get('cl6')} adds an entry with no page")
    return rows


def _add(out, name, r, source):
    """Create row r's entry in out[name] (the kind's file, made when the book has none); a no-op when its id is there."""
    from lxml import etree

    from importer.sr6 import KINDS, NS
    a, kind = r["add"], r["kind"]
    if source is None:
        print(f"override {r['cl6']}: add needs a recipe id", file=sys.stderr)
        return
    if out.get(name):
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
    else:
        root = etree.fromstring(f'<sr6:data xmlns:sr6="{NS}" kind="{kind}" version="1"/>'.encode())
    ename = a.get("name", r["cl6"])
    eid = slug(ename)
    if any(e.get("id") == eid for e in root if isinstance(e.tag, str)):
        print(f"override {r['cl6']}: {eid} already in {name}, left as is", file=sys.stderr)
        return
    e = etree.SubElement(root, KINDS[kind], {"id": eid, "source": source, "page": str(a["page"]),
                                             **{k: str(v) for k, v in a.get("attrs", {}).items()}})
    etree.SubElement(e, "name").text = ename
    for k in a.get("kids", []):
        etree.SubElement(e, k["tag"], {x: str(v) for x, v in k.get("attrs", {}).items()}).text = k.get("text")
    out[name] = dump(out.get(name), root)


def texts(recipe_id, files, texts_xml, rows=None):
    """texts_xml (the book's texts file, ids unscoped) with a <text> for each add row that has "text_from": the text the
    book already has for the catalog entry of that name, under the new entry's kind and id. Nothing is invented: no
    such heading or no text for it leaves the entry without one (reported on stderr)."""
    rows = [r for r in (table(recipe_id) if rows is None else check(rows)) if r.get("add", {}).get("text_from")]
    if not rows or not texts_xml:
        return texts_xml
    have = {(of, i): t for of, i, t in xmlio.texts_entries(texts_xml)}
    heads = {}
    for fname, xml in files.items():
        for m in re.finditer(r'<\w+ id="([^"]+)"[^>]*><name>([^<]*)</name>', xml or ""):
            heads.setdefault(norm(unescape(m.group(2))), (fname[:-4], m.group(1)))
    add = ""
    for r in rows:
        a = r["add"]
        new = (r["kind"], slug(a.get("name", r["cl6"])))
        src = have.get(heads.get(norm(a["text_from"])))
        if new in have:
            continue
        if not src:
            print(f"override {r['cl6']}: no text under {a['text_from']!r}", file=sys.stderr)
            continue
        add += f"  <text of={quoteattr(new[0])} id={quoteattr(new[1])}>{escape(src)}</text>{chr(10)}"
    i = texts_xml.rindex("</sr6:data>")
    return texts_xml[:i] + add + texts_xml[i:]


def table(recipe_id):
    p = DIR / f"{(recipe_id or '').lower()}.json"
    return check(json.loads(p.read_text(encoding="utf8"))) if p.is_file() else []


def _set_by_id(out, rows):
    """The id rows applied: out[<kind>.xml] with each entry of an id the rows name given its attributes."""
    from lxml import etree
    want = {}
    for r in rows:
        want.setdefault(f"{r['kind']}.xml", {})[r["id"]] = r["set"]
    missing = []
    for name, ids in want.items():
        if not out.get(name):
            missing += [f"{name}:{i}" for i in ids]
            continue
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
        seen = set()
        for e in root:
            if isinstance(e.tag, str) and e.get("id") in ids:
                seen.add(e.get("id"))
                for k, v in ids[e.get("id")].items():
                    e.set(k, str(v))
        missing += [f"{name}:{i}" for i in ids if i not in seen]
        out[name] = dump(out[name], root)
    if missing:
        print(f"override: {len(missing)} id rows found no entry ({', '.join(missing[:6])}{' ...' if len(missing) > 6 else ''})", file=sys.stderr)


def apply(recipe_id, files, rows=None):
    """files ({<kind>.xml: xml}) with the recipe's override rows applied."""
    rows = table(recipe_id) if rows is None else check(rows)
    if not rows:
        return files
    from lxml import etree
    out = dict(files)
    for r in rows:
        name = f"{r['kind']}.xml"
        if "id" in r:
            continue
        if "add" in r:
            _add(out, name, r, recipe_id.upper() if recipe_id else None)
            continue
        if not out.get(name):
            print(f"override {r['cl6']}: no {name}", file=sys.stderr)
            continue
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
        for want in r["ours"]:
            hit = [e for e in root if isinstance(e.tag, str) and norm(e.findtext("name") or "") == norm(want)]
            if not hit:
                print(f"override {r['cl6']}: no {want!r} in {name}", file=sys.stderr)
            for e in hit:
                have = {norm(a.text or "") for a in e.findall("alias")} | {norm(e.findtext("name") or "")}
                if norm(r["cl6"]) not in have:
                    _add_kid(e, "alias", {}, r["cl6"])  # (before the entry's text, after its other aliases)
                for k, v in r.get("set", {}).items():
                    e.set(k, str(v))
        out[name] = dump(out[name], root)
    _set_by_id(out, [r for r in rows if "id" in r])  # (after the adds: a created entry takes its class too)
    return out

