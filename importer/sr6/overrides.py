"""Per-book override tables (importer/sr6/overrides/<recipe id>.json, lower case; absent = empty): a last resort, applied
after the import reads a book. Each row maps a Commlink6 name to our item(s), source-scoped (one table per recipe):
  {"cl6": "<Commlink6's name>", "kind": "<catalog file stem>", "ours": ["<our entry's printed name>", ...],
   "set": {"<attribute>": "<value taken from Commlink6>"}}   ("set" optional)
It adds the Commlink6 name as an <alias> child (a name only) to each entry of `ours`, and sets the listed attributes.
A row with "add" instead of "ours" CREATES an entry the books print only inside other items' text (Commlink6 has it):
  {"cl6": "<Commlink6's name>", "kind": "<catalog file stem>", "add": {"page": <int>, "attrs": {...rule data from
   Commlink6}, "kids": [{"tag": "effect|choice|alias|...", "attrs": {...}}], "name": "<optional, default cl6>"}}
id = slug(name) (scoped to the source by the importer); an id already in the file is left alone (logged). No text of
any kind is written: the entry's description, if the book has one, comes from the texts step. "text_from": "<heading
name>" (a name, never text) in an add row gives the entry the description the book's text already has under that
heading (`texts()`: the owner's PDF text of the catalog entry of that name, copied to the new entry).
A row with "id" (an entry's unscoped id, the importer's own) and "set" {"class": "<TYPE/SUBTYPE>"} sets Commlink6's
classification on that entry (rows made by tools/cl6check/classmap.py carry "gen": "class"); an id no entry has is
reported once on stderr, nothing guessed.
An id row with "gen": "value" or "family" (made by tools/cl6check/valuemap.py and familymap.py) sets printed values taken from Commlink6 (VALUE_ATTRS:
cost, avail, karma, dv, ar …; the owner's rule: where the book and the reviewers could not confirm ours) and optional
"formula" {"<field>": "<expr>"} (a per-rating table as a tier(), see docs/sr6-data-format.md). The entry's own <formula>,
<issue> and <found> children for each field set go (they described the value being replaced).
Further ops on the entries of a kind, by their unscoped id (docs/sr6-data-format.md):
  {"kind","id","remove":true}                     the entry goes (its aliases with it, its text in `texts()`)
  {"kind","merge":{"into","from","from_kind"}}    the attributes `into` lacks come from `from` (the table's copy), which goes
  {"kind","id","rename":"<name>"}                 a new name (names only); the old one stays as an alias unless "alias": false
  {"move_kind":{"id","from","to"}}                the entry re-filed in another kind's file (gear -> weapons: a melee weapon; armor -> gear)
A description is never an override: "set" and "add" refuse a text field. See docs/sr6-data-format.md."""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape, quoteattr, unescape

from importer import xmlio
from importer.sr6.ids import slug
from importer.sr6.regroup import norm
from importer.sr6.resolve import _add_kid

DIR = Path(__file__).with_name("overrides")
OPS = ("remove", "rename", "merge", "move_kind")
SETTABLE = {"class"}  # (what an id row may set)
KID_TAGS = {"slot", "fits", "variant", "relevance", "flag", "modifier", "prerequisite", "selection"}  # (a "gen": "family" row's "kids": Commlink6's item structure)
VALUE_ATTRS = {"cost", "avail", "karma", "karmaMax", "essence", "capacity", "rating", "dv", "ar", "modes", "ammo", "defense",
               "seats", "range", "type", "duration", "category", "action", "activation", "fade", "threshold", "kind",
               "handling", "interval", "power", "attr", "skill", "spec", "social", "modonly", "size", "ammoClass", "accel", "speed", "body", "armor", "pilot", "sensor"}  # (a "gen": "value" row)
CLASS_KEY = re.compile(r"[A-Za-z0-9_]+(/[A-Za-z0-9_]+)?")
NO_TEXT = {"description", "desc", "text", "summary"}  # (descriptions come from the owner's PDF, never from here)


def dump(old, root):
    """The xml of `root` as the file `old` had it: its header comment (`Generated by the importer …`) kept."""
    from lxml import etree
    lead = re.match(r"(?:<\?xml[^>]*\?>\s*)?((?:<!--.*?-->\s*)*)", old or "", re.S).group(1)
    return xmlio.HEAD + lead + etree.tostring(root, encoding="unicode").rstrip(chr(10)) + chr(10)


def check(rows):
    for r in rows:
        if bad := NO_TEXT & {k.lower() for k in r.get("set", {})}:
            raise ValueError(f"override of {r.get('cl6')} sets a description field ({sorted(bad)})")
        if "id" in r and r.get("gen") in ("value", "family", "owner") and not any(k in r for k in OPS):
            if not (r.get("set") or r.get("kids")) or set(r.get("set", {})) - VALUE_ATTRS or set(r.get("formula", {})) - VALUE_ATTRS:
                raise ValueError(f"override of {r.get('id')}: a value row sets {sorted(VALUE_ATTRS)} only")
            if bad := [k for k in r.get("kids", []) if k.get("tag") not in KID_TAGS]:
                raise ValueError(f"override of {r.get('id')}: kids are {sorted(KID_TAGS)} only")
        elif "id" in r and not any(k in r for k in OPS):
            if not r.get("set") or set(r["set"]) - SETTABLE or not all(CLASS_KEY.fullmatch(str(v)) for v in r["set"].values()):
                raise ValueError(f"override of {r.get('id')}: an id row sets {sorted(SETTABLE)} only")
        if "rename" in r and not (isinstance(r["rename"], str) and 0 < len(r["rename"]) <= 120 and chr(10) not in r["rename"]):
            raise ValueError(f"override of {r.get('id')}: rename is a name")
        if bad := NO_TEXT & {k.lower() for v in (r.get("merge"), r.get("move_kind")) if isinstance(v, dict) for k in v}:
            raise ValueError(f"override of {r.get('id')}: an op names a description field ({sorted(bad)})")
        if a := r.get("add"):
            names = {k.lower() for k in a} | {k.lower() for k in a.get("attrs", {})} | {k["tag"].lower() for k in a.get("kids", [])}
            if bad := NO_TEXT & names:
                raise ValueError(f"override of {r.get('cl6')} adds a description field ({sorted(bad)})")
            if not (isinstance(a.get("text_from", ""), str) and len(a.get("text_from", "")) <= 80 and chr(10) not in a.get("text_from", "")):
                raise ValueError(f"override of {r.get('cl6')}: text_from is a heading name")
            if not isinstance(a.get("page"), int):
                raise ValueError(f"override of {r.get('cl6')} adds an entry with no page")
    return rows


def _add(out, name, r, source):
    """Create row r's entry in out[name] (the kind's file, made when the book has none); a no-op when its id is there."""
    from lxml import etree

    from importer.sr6 import KINDS, NS
    a, kind = r["add"], r["kind"]
    if source is None:
        print(f"override {r['cl6']}: add needs a recipe id", file=sys.stderr)
        return
    if out.get(name):
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
    else:
        root = etree.fromstring(f'<sr6:data xmlns:sr6="{NS}" kind="{kind}" version="1"/>'.encode())
    ename = a.get("name", r["cl6"])
    eid = a.get("id") or slug(ename)  # (an id of its own when another entry has the name: a rigger program Encryption)
    if any(e.get("id") == eid for e in root if isinstance(e.tag, str)):
        print(f"override {r['cl6']}: {eid} already in {name}, left as is", file=sys.stderr)
        return
    e = etree.SubElement(root, KINDS[kind], {"id": eid, "source": source, "page": str(a["page"]),
                                             **{k: str(v) for k, v in a.get("attrs", {}).items()}})
    etree.SubElement(e, "name").text = ename
    for k in a.get("kids", []):
        etree.SubElement(e, k["tag"], {x: str(v) for x, v in k.get("attrs", {}).items()}).text = k.get("text")
    out[name] = dump(out.get(name), root)


def texts(recipe_id, files, texts_xml, rows=None):
    """texts_xml (the book's texts file, ids unscoped) with a <text> for each add row that has "text_from": the text the
    book already has for the catalog entry of that name, under the new entry's kind and id; and without the text of an
    entry a remove or merge row took out. Nothing is invented: no such heading or no text for it leaves the entry without
    one (reported on stderr)."""
    every = table(recipe_id) if rows is None else check(rows)
    rows = [r for r in every if r.get("add", {}).get("text_from")]
    gone = {(r["kind"], r["id"]) for r in every if r.get("remove")} | {(r["merge"].get("from_kind", r["kind"]), r["merge"]["from"]) for r in every if "merge" in r}
    if not texts_xml or not (rows or gone):
        return texts_xml
    for of, i in gone:
        texts_xml = re.sub(r"[ \t]*<text of=%s id=%s>.*?</text>\n?" % (re.escape(quoteattr(of)), re.escape(quoteattr(i))), "", texts_xml, flags=re.S)
    have = {(of, i): t for of, i, t in xmlio.texts_entries(texts_xml)}
    heads = {}
    for fname, xml in files.items():
        for m in re.finditer(r'<\w+ id="([^"]+)"[^>]*><name>([^<]*)</name>', xml or ""):
            heads.setdefault(norm(unescape(m.group(2))), (fname[:-4], m.group(1)))
    add = ""
    for r in rows:
        a = r["add"]
        new = (r["kind"], slug(a.get("name", r["cl6"])))
        src = have.get(heads.get(norm(a["text_from"])))
        if new in have:
            continue
        if not src:
            print(f"override {r['cl6']}: no text under {a['text_from']!r}", file=sys.stderr)
            continue
        add += f"  <text of={quoteattr(new[0])} id={quoteattr(new[1])}>{escape(src)}</text>{chr(10)}"
    i = texts_xml.rindex("</sr6:data>")
    return texts_xml[:i] + add + texts_xml[i:]


def table(recipe_id):
    p = DIR / f"{(recipe_id or '').lower()}.json"
    return check(json.loads(p.read_text(encoding="utf8"))) if p.is_file() else []


def _set_by_id(out, rows):
    """The id rows applied: out[<kind>.xml] with each entry of an id the rows name given its attributes."""
    from lxml import etree
    want, forms, vals, kids = {}, {}, {}, {}
    homes = {}
    for fname, xml in out.items():  # (an entry's own file: a row's kind is Commlink6's, and the importer may file it under another)
        for m in re.finditer(r'<\w+ id="([^"]+)"', xml or ""):
            homes.setdefault(m.group(1), []).append(fname)
    for r in rows:
        if f"{r['kind']}.xml" not in homes.get(r["id"], []) and len(homes.get(r["id"], [])) == 1:
            r = {**r, "kind": homes[r["id"]][0][:-4]}
        if r["kind"] == "gear" and "social" in r.get("set", {}):  # (an armor the importer filed as gear has no social rating: the schema lacks it)
            r = {**r, "set": {k: v for k, v in r["set"].items() if k != "social"}}
        want.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], {}).update(r.get("set", {}))
        if r.get("kids"):
            kids.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], []).extend(r["kids"])
        if r.get("gen") in ("value", "family", "owner"):
            forms.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], {}).update(r.get("formula", {}))
            vals.setdefault(f"{r['kind']}.xml", {}).setdefault(r["id"], set()).update(r.get("set", {}))
    missing = []
    for name, ids in want.items():
        if not out.get(name):
            missing += [f"{name}:{i}" for i in ids]
            continue
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
        seen = set()
        for e in root:
            if isinstance(e.tag, str) and e.get("id") in ids:
                seen.add(e.get("id"))
                for k, v in ids[e.get("id")].items():
                    e.set(k, str(v))
                for k in vals.get(name, {}).get(e.get("id"), ()):
                    for c in [c for c in e if c.tag in ("formula", "issue", "found") and c.get("field") == k]:
                        e.remove(c)  # (the value they described is replaced)
                    if k == "karma":
                        e.attrib.pop("karmaMax", None)
                for k in kids.get(name, {}).get(e.get("id"), []):  # (a structure child the entry lacks, before its <text>)
                    attrs = {x: str(v) for x, v in k.get("attrs", {}).items()}
                    if any(c.tag == k["tag"] and dict(c.attrib) == attrs and (c.text or "") == (k.get("text") or "") for c in e):
                        continue
                    c = etree.Element(k["tag"], attrs)
                    c.text = k.get("text")
                    t = e.find("text")
                    e.insert(list(e).index(t) if t is not None else len(e), c)
                for k, expr in forms.get(name, {}).get(e.get("id"), {}).items():
                    f = etree.Element("formula", {"field": k})
                    f.text = expr
                    e.insert(sum(1 for c in e if c.tag in ("name", "alias", "formula")), f)
        missing += [f"{name}:{i}" for i in ids if i not in seen]
        out[name] = dump(out[name], root)
    if missing:
        print(f"override: {len(missing)} id rows found no entry ({', '.join(missing[:6])}{' ...' if len(missing) > 6 else ''})", file=sys.stderr)


MOVE_DROP = {("gear", "weapons"): {"capacity", "karma", "per", "slots", "energy"},  # (an entry's attributes the target kind's schema lacks)
             ("armor", "gear"): {"defense", "social"}}
SPECS = {"BLADES": "Blades", "CLUBS": "Clubs", "UNARMED": "Unarmed", "OTHER_CLOSE": "Other"}


def _load(out, name, kind):
    """(the file's root, its xml as it was): a new file when there is none."""
    from lxml import etree
    from importer.sr6 import NS
    if out.get(name):
        return etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8")), out[name]
    return etree.fromstring(f'<sr6:data xmlns:sr6="{NS}" kind="{kind}" version="1"/>'.encode()), ""


def _find(root, eid):
    return next((e for e in root if isinstance(e.tag, str) and e.get("id") == eid), None)


def _ops(out, rows):
    """The remove, merge, rename and move_kind rows applied, in that order (a merge before the move that files its target
    as a weapon). A row whose entry isn't there is reported once, nothing guessed."""
    from importer.sr6 import KINDS
    lost = []
    for r in (x for x in rows if x.get("remove")):
        name = f"{r['kind']}.xml"
        root, old = _load(out, name, r["kind"])
        e = _find(root, r["id"])
        if e is None:
            lost.append(f"remove {name}:{r['id']}")
            continue
        root.remove(e)
        out[name] = dump(old, root)
    for r in (x for x in rows if "merge" in x):
        m = r["merge"]
        into, src = f"{r['kind']}.xml", f"{m.get('from_kind', r['kind'])}.xml"
        ri, oi = _load(out, into, r["kind"])
        rs, os_ = _load(out, src, m.get("from_kind", r["kind"]))
        a, b = _find(ri, m["into"]), _find(rs, m["from"])
        if a is None or b is None:
            lost.append(f"merge {into}:{m['into']} <- {src}:{m['from']}")
            continue
        for k, v in b.attrib.items():
            if k not in ("id", "source", "page", "class", "group") and not a.get(k) and v:
                a.set(k, v)
        rs.remove(b)
        out[into], out[src] = dump(oi, ri), dump(os_, rs)
    for r in (x for x in rows if "rename" in x):
        name = f"{r['kind']}.xml"
        root, old = _load(out, name, r["kind"])
        e = _find(root, r["id"])
        if e is None:
            lost.append(f"rename {name}:{r['id']}")
            continue
        n = e.find("name")
        was = (n.text or "").strip()
        if was != r["rename"]:
            n.text = r["rename"]
            if r.get("alias", True) and was and norm(was) not in {norm(x.text or "") for x in e.findall("alias")} | {norm(r["rename"])}:
                _add_kid(e, "alias", {}, was)
            out[name] = dump(old, root)
    for r in (x for x in rows if "move_kind" in x):
        m = r["move_kind"]
        src, dst = f"{m['from']}.xml", f"{m['to']}.xml"
        if (m["from"], m["to"]) not in MOVE_DROP:
            lost.append(f"move_kind {m['from']} to {m['to']} (only gear to weapons, armor to gear)")
            continue
        rs, os_ = _load(out, src, m["from"])
        rd, od = _load(out, dst, m["to"])
        e = _find(rs, m["id"])
        if e is None:
            lost.append(f"move_kind {src}:{m['id']}")
            continue
        if _find(rd, m["id"]) is not None:
            lost.append(f"move_kind {m['id']}: {dst} has it already")
            continue
        e.tag = KINDS[m["to"]]
        for k in MOVE_DROP[m["from"], m["to"]]:
            e.attrib.pop(k, None)
        if m["to"] == "weapons":  # (a melee weapon: Close Combat, its specialization from its class)
            sub = (e.get("class") or "").split("/")[-1]
            spec = SPECS.get(sub) or SPECS.get((e.get("type") or "").upper())
            e.set("skill", "Close Combat")
            if spec:
                e.set("spec", spec)
        rs.remove(e)
        rd.append(e)
        out[src], out[dst] = dump(os_, rs), dump(od, rd)
    if lost:
        print(f"override: {len(lost)} op rows found no entry ({'; '.join(lost[:6])}{' ...' if len(lost) > 6 else ''})", file=sys.stderr)


def apply(recipe_id, files, rows=None):
    """files ({<kind>.xml: xml}) with the recipe's override rows applied."""
    rows = table(recipe_id) if rows is None else check(rows)
    if not rows:
        return files
    from lxml import etree
    out = dict(files)
    for r in rows:
        if "id" in r or any(k in r for k in OPS):
            continue
        name = f"{r['kind']}.xml"
        if "add" in r:
            _add(out, name, r, recipe_id.upper() if recipe_id else None)
            continue
        if not out.get(name):
            print(f"override {r['cl6']}: no {name}", file=sys.stderr)
            continue
        root = etree.fromstring(re.sub(r"^<\?xml[^>]*\?>\s*", "", out[name]).encode("utf8"))
        for want in r["ours"]:
            hit = [e for e in root if isinstance(e.tag, str) and norm(e.findtext("name") or "") == norm(want)]
            if not hit:
                print(f"override {r['cl6']}: no {want!r} in {name}", file=sys.stderr)
            for e in hit:
                have = {norm(a.text or "") for a in e.findall("alias")} | {norm(e.findtext("name") or "")}
                if norm(r["cl6"]) not in have:
                    _add_kid(e, "alias", {}, r["cl6"])  # (before the entry's text, after its other aliases)
                for k, v in r.get("set", {}).items():
                    e.set(k, str(v))
        out[name] = dump(out[name], root)
    _ops(out, [r for r in rows if any(k in r for k in ("remove", "merge"))])
    _set_by_id(out, [r for r in rows if "id" in r and ("set" in r or "kids" in r) and not any(k in r for k in OPS)])  # (after the adds: a created entry takes its class too)
    _ops(out, [r for r in rows if any(k in r for k in ("rename", "move_kind"))])
    return out

